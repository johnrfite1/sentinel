/**
 * What a failed signer check *does* depends on which of three tiers it belongs to. This
 * taxonomy is the most security-relevant decision in the signer, so it is stated once,
 * here, rather than being implied by scattered `if` statements.
 *
 * FATAL — the request is internally inconsistent or addressed to a different system.
 *   The signer cannot honestly attest to anything, including a BLOCK. No receipt is
 *   produced for any verdict.
 *
 * EXECUTABILITY — the receipt could not possibly be executed, or the signer is not the
 *   key the vault currently recognises. ALLOW and REVIEW are refused, because both are
 *   execution paths (a REVIEW receipt executes with an owner override, §3.3(7)). BLOCK
 *   is still signed: a block receipt is evidence, never authority, and evidence about a
 *   stale action is still true evidence.
 *
 * CONFORMANCE — a finding the *evaluator* is supposed to have weighed. ALLOW is refused,
 *   because §3.3(8) requires that stale, conflicting, or unverifiable state never produce
 *   an automatic allow. REVIEW is permitted, and this is load-bearing rather than lax:
 *   Case 4 (§4.2) is triggered by exactly these conditions — a changed target code hash,
 *   a proxy target, conflicting anchored state — and its expected result is a REVIEW
 *   receipt. A signer that refused to sign on a code-hash mismatch would make Case 4
 *   unreachable, i.e. it would break the spec while looking stricter.
 *
 * The asymmetry is deliberate and worth restating: severity bounds what the signer will
 * ATTEST to. It never widens it. There is no tier at which a failing check makes an
 * ALLOW more likely.
 */
export type Severity = "FATAL" | "EXECUTABILITY" | "CONFORMANCE";

