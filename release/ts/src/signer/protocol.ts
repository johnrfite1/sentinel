export class ProtocolError extends Error {}

function fail(path: string, expected: string): never {
    throw new ProtocolError(`${path}: expected ${expected}`);
}

function obj(v: unknown, path: string): Record<string, unknown> {
    if (typeof v !== "object" || v === null || Array.isArray(v)) fail(path, "an object");
    return v as Record<string, unknown>;
}

/** Decimal-string → bigint. Rejects hex, signs, exponents, and anything else clever. */
function uint(v: unknown, path: string): bigint {
    if (typeof v !== "string" || !/^(0|[1-9][0-9]*)$/.test(v)) {
        fail(path, "an unsigned decimal integer string");
    }
    return BigInt(v);
}

/**
 * Reject strings containing an unpaired UTF-16 surrogate.
 *
 * A-044. `evidenceHash` is `keccak256(stringToBytes(evidenceCanonical))`, and viem's
 * `stringToBytes` is `TextEncoder.encode`, which replaces EVERY unpaired surrogate with
 * U+FFFD. So `"x\ud800y"` and `"x\udbffy"` encode to the same bytes and hash identically —
 * verified directly. All 2,048 lone surrogates collapse to one sequence, so k of them give
 * 2048^k distinct bundles sharing an `evidenceHash`, and the receipt's commitment to its
 * evidence stops being injective.
 *
 * Symmetry with the independent verifier is the second reason and arguably the better one:
 * the D-010 CLI now rejects lone surrogates under RFC 8785 §3.2.2.2, where such data "MUST
 * cause a compliant JCS implementation to terminate with an appropriate error". Before this
 * check the signer would sign evidence that verifier structurally could not reproduce — a
 * genuine receipt reading as FAILED. Both sides now agree on what is signable.
 *
 * This does NOT establish that the string is canonical JSON; §5.6 requires that and the
 * signer still takes the caller's word for it. Stated so the check is not over-read.
 */
function wellFormed(s: string, path: string): string {
    if (/[\uD800-\uDFFF]/.test(s.replace(/[\uD800-\uDBFF][\uDC00-\uDFFF]/g, ""))) {
        fail(path, "well-formed UTF-16 with no unpaired surrogate (RFC 8785 §3.2.2.2)");
    }
    return s;
}

function bounded(v: unknown, path: string, bits: number): bigint {
    const n = uint(v, path);
    if (n >= 1n << BigInt(bits)) fail(path, `a uint${bits}`);
    return n;
}

function hex(v: unknown, path: string, bytes?: number): Hex {
    if (typeof v !== "string" || !/^0x[0-9a-fA-F]*$/.test(v)) fail(path, "a 0x-prefixed hex string");
    // ODD LENGTHS ARE REJECTED, and this is not pedantry. `callData` has no fixed byte
    // length, and viem's `toBytes` left-pads an odd-length hex string with a leading zero
    // nibble — so "0xdeadbeef1" hashes as the five bytes 0x0deadbeef1 while a text-level
    // `slice(0, 10)` reads the selector as 0xdeadbeef. The signer would then check the
    // mandate's selector and the vault's allowlist against four bytes that are NOT the first
    // four bytes of the calldata it committed to in `dataHash`. Found by adversarial review.
    if (v.length % 2 !== 0) fail(path, "an even number of hex digits (whole bytes)");
    if (bytes !== undefined && v.length !== 2 + bytes * 2) fail(path, `${bytes} bytes of hex`);
    return v.toLowerCase() as Hex;
}

function address(v: unknown, path: string): Hex {
    return hex(v, path, 20);
}

function bool(v: unknown, path: string): boolean {
    if (typeof v !== "boolean") fail(path, "a boolean");
    return v;
}

function str(v: unknown, path: string): string {
    if (typeof v !== "string") fail(path, "a string");
    return v;
}

/**
 * Rejects fields the signer does not understand instead of ignoring them.
 *
 * A dropped field is how one payload comes to mean two things to two components — the
 * evaluator believes it constrained something, the signer never saw it, and the receipt
 * attests to the weaker reading. Strictness here is cheap; the failure it prevents is not.
 */
function noExtras(o: Record<string, unknown>, allowed: readonly string[], path: string): void {
    for (const k of Object.keys(o)) {
        if (!allowed.includes(k)) throw new ProtocolError(`${path}: unexpected field ${JSON.stringify(k)}`);
    }
}

const MANDATE_FIELDS = [
    "schemaVersion", "mandateId", "principal", "signer", "vault", "chainId", "target", "targetCodeHash",
    "selector", "maxNativeValueWei", "purposeKind", "resourceId", "beneficiary", "durationSeconds",
    "recurringAllowed", "validAfter", "validUntil", "policyHash",
] as const;

export function parseMandate(v: unknown, path = "mandate"): MandatePayload {
    const o = obj(v, path);
    noExtras(o, MANDATE_FIELDS, path);
    return {
        schemaVersion: bounded(o.schemaVersion, `${path}.schemaVersion`, 16),
        mandateId: hex(o.mandateId, `${path}.mandateId`, 32),
        principal: address(o.principal, `${path}.principal`),
        signer: address(o.signer, `${path}.signer`),
        vault: address(o.vault, `${path}.vault`),
        chainId: bounded(o.chainId, `${path}.chainId`, 256),
        target: address(o.target, `${path}.target`),
        targetCodeHash: hex(o.targetCodeHash, `${path}.targetCodeHash`, 32),
        selector: hex(o.selector, `${path}.selector`, 4),
        maxNativeValueWei: bounded(o.maxNativeValueWei, `${path}.maxNativeValueWei`, 256),
        purposeKind: hex(o.purposeKind, `${path}.purposeKind`, 32),
        resourceId: hex(o.resourceId, `${path}.resourceId`, 32),
        beneficiary: address(o.beneficiary, `${path}.beneficiary`),
        durationSeconds: bounded(o.durationSeconds, `${path}.durationSeconds`, 64),
        recurringAllowed: bool(o.recurringAllowed, `${path}.recurringAllowed`),
        validAfter: bounded(o.validAfter, `${path}.validAfter`, 64),
        validUntil: bounded(o.validUntil, `${path}.validUntil`, 64),
        policyHash: hex(o.policyHash, `${path}.policyHash`, 32),
    };
}

const POLICY_FIELDS = [
    "schemaVersion", "policyVersion", "vault", "chainId", "allowedOperation", "allowedTargetsHash",
    "allowedSelectorsHash", "maxNativeValueWei", "maxAllowanceIncreaseBaseUnits",
    "allowedCallGraphHash", "validAfter", "validUntil", "failureMode",
] as const;

export function parsePolicy(v: unknown, path = "policy"): PolicyPayload {
    const o = obj(v, path);
    noExtras(o, POLICY_FIELDS, path);
    return {
        schemaVersion: bounded(o.schemaVersion, `${path}.schemaVersion`, 16),
        policyVersion: bounded(o.policyVersion, `${path}.policyVersion`, 32),
        vault: address(o.vault, `${path}.vault`),
        chainId: bounded(o.chainId, `${path}.chainId`, 256),
        allowedOperation: bounded(o.allowedOperation, `${path}.allowedOperation`, 8),
        allowedTargetsHash: hex(o.allowedTargetsHash, `${path}.allowedTargetsHash`, 32),
        allowedSelectorsHash: hex(o.allowedSelectorsHash, `${path}.allowedSelectorsHash`, 32),
        maxNativeValueWei: bounded(o.maxNativeValueWei, `${path}.maxNativeValueWei`, 256),
        // `bounded(..., 256)`, not `uint()` (A-068). Both fields are `uint256` on the wire and
        // both escaped the bound: an out-of-range value parsed fine and then threw inside
        // `leftPad` at signing time, giving a SIGNER_ERROR from within the signing routine
        // rather than a BAD_REQUEST at the boundary — which is exactly the defect A-044 fixed
        // for the other four integer fields and did not reach these two. The consequence is
        // D-012's: the one request a caller could trigger at will produced NO signed refusal
        // record, in the component whose record exists to make refusals provable.
        maxAllowanceIncreaseBaseUnits: bounded(
            o.maxAllowanceIncreaseBaseUnits, `${path}.maxAllowanceIncreaseBaseUnits`, 256),
        allowedCallGraphHash: hex(o.allowedCallGraphHash, `${path}.allowedCallGraphHash`, 32),
        validAfter: bounded(o.validAfter, `${path}.validAfter`, 64),
        validUntil: bounded(o.validUntil, `${path}.validUntil`, 64),
        failureMode: bounded(o.failureMode, `${path}.failureMode`, 8),
    };
}

