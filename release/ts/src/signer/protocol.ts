const REQUEST_FIELDS = ["action", "callData", "mandate", "policy", "evaluation", "ttlSeconds"] as const;
const EVALUATION_FIELDS = [
    "verdict", "reasonCodes", "evidenceCanonical", "simulationBlockNumber", "simulationBlockHash",
] as const;

export function parseEvaluateAndSignRequest(v: unknown): EvaluateAndSignRequest {
    const o = obj(v, "params");
    noExtras(o, REQUEST_FIELDS, "params");

    const ev = obj(o.evaluation, "params.evaluation");
    noExtras(ev, EVALUATION_FIELDS, "params.evaluation");

    const verdict = str(ev.verdict, "params.evaluation.verdict");
    // `Object.hasOwn`, NOT `in` (A-061). `in` walks the prototype chain, so `__proto__`,
    // `toString`, `constructor` and every other Object.prototype member passed here as a legal
    // verdict name. The consequence was not cosmetic: on the refusal path the signer produced a
    // genuinely SIGNED §5.5.1 RefusalRecord whose `requestedVerdict` sits outside the published
    // schema, and the ratified D-010 verifier enforces that schema — so an unauthenticated
    // caller could choose a value that makes the signer's own proof-of-refusal unverifiable,
    // which is precisely what D-012's record exists to prevent. On the attest path the same
    // value reached `BigInt(verdictNumber(v))` and threw, returning SIGNER_ERROR from inside
    // the signing routine rather than BAD_REQUEST at the boundary.
    if (!Object.hasOwn(VERDICT, verdict)) fail("params.evaluation.verdict", "one of ALLOW, REVIEW, BLOCK");

    if (!Array.isArray(ev.reasonCodes)) fail("params.evaluation.reasonCodes", "an array");
    const reasonCodes = ev.reasonCodes.map((c, i) => {
        const code = str(c, `params.evaluation.reasonCodes[${i}]`);
        // Rejected at the boundary, so a malformed code is a BAD_REQUEST the caller can fix
        // rather than a signing-time throw. See REASON_CODE_PATTERN for why the shape is
        // load-bearing rather than cosmetic.
        if (!REASON_CODE_PATTERN.test(code)) {
            fail(`params.evaluation.reasonCodes[${i}]`, `to match ${REASON_CODE_PATTERN.source}`);
        }
        // THE SIGNER'S NAMESPACE IS THE SIGNER'S (A-044).
        //
        // `reasonCodesHash` commits to the UNION of the caller's codes and the signer's own
        // findings, and `signerFindings` is returned over the RPC but is NOT a field of the
        // signed §5.4 payload — so a third party reading a receipt cannot tell which side
        // contributed a code. Nothing rejected a caller-supplied `SIGNER_` prefix, and
        // `REASON_CODE_PATTERN` happily accepts one.
        //
        // An adversarial reviewer signed an ALLOW whose committed codes read
        // SIGNER_VAULT_PAUSED, SIGNER_MANDATE_NOT_ACTIVE and SIGNER_NOT_ACTIVE_SIGNER while
        // the signer had found nothing — an authenticated receipt asserting the signer said
        // three things it never said, and allowed anyway. Verdicts are unaffected
        // (`refusesVerdict` consults the signer's own findings only), which is exactly why
        // this is an integrity defect in the RECORD rather than a bypass.
        if (code.startsWith("SIGNER_")) {
            fail(
                `params.evaluation.reasonCodes[${i}]`,
                "not to use the SIGNER_ prefix, which is reserved for the signer's own findings",
            );
        }
        return code;
    });

    return {
        action: parseAction(o.action, "params.action"),
        callData: hex(o.callData, "params.callData"),
        mandate: parseMandate(o.mandate, "params.mandate"),
        policy: parsePolicy(o.policy, "params.policy"),
        evaluation: {
            verdict: verdict as VerdictName,
            reasonCodes,
            evidenceCanonical: wellFormed(
                str(ev.evidenceCanonical, "params.evaluation.evidenceCanonical"),
                "params.evaluation.evidenceCanonical",
            ),
            simulationBlockNumber: bounded(
                ev.simulationBlockNumber, "params.evaluation.simulationBlockNumber", 256),
            simulationBlockHash: hex(
                ev.simulationBlockHash, "params.evaluation.simulationBlockHash", 32),
        },
        ttlSeconds: o.ttlSeconds === undefined ? undefined : uint(o.ttlSeconds, "params.ttlSeconds"),
    };
}

