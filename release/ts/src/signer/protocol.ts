export interface EvaluateAndSignRequest {
    action: ActionPayload;
    /** The complete calldata. The signer hashes it; it never trusts action.dataHash. */
    callData: Hex;
    /** The mandate the evaluator believes is active. Its hash is checked against the vault. */
    mandate: MandatePayload;
    /** The policy the evaluator believes is active. Its hash is checked against the vault. */
    policy: PolicyPayload;
    evaluation: {
        verdict: VerdictName;
        /** The evaluator's own reason codes. The signer appends its findings and hashes the union. */
        reasonCodes: string[];
        /**
         * The canonical evidence-bundle bytes (§5.6: RFC 8785 JSON), passed in full.
         *
         * The signer hashes these itself rather than accepting an `evidenceHash`. Accepting
         * a caller-supplied 32 bytes would be a narrow but real generic-signing surface —
         * "put these bytes inside a structure I will sign" — and the whole point of A-005
         * is that no such surface exists. The cost is that the bundle crosses a local
         * socket; the benefit is that the signer never signs a digest it did not compute.
         */
        evidenceCanonical: string;
        simulationBlockNumber: bigint;
        simulationBlockHash: Hex;
    };
    /** Requested receipt lifetime. Clamped by the signer to its max and to the action deadline. */
    ttlSeconds?: bigint;
}

export interface SignedReceipt {
    receipt: DecisionReceiptPayload;
    signature: Hex;
    /** The exact ordered list that `reasonCodesHash` commits to, so a verifier can recompute it. */
    reasonCodes: string[];
    actionHash: Hex;
    evidenceHash: Hex;
    /** The signer's findings, separated from the evaluator's for the audit trail. */
    signerFindings: ReasonCode[];
}

/**
 * §D-012. Proof that the signer saw a request and declined it.
 *
 * WHY THIS EXISTS. Before D-012 a refusal produced only an absent receipt, so "the signer
 * refused" and "the signer was never asked" were indistinguishable — meaning Gate S2 could
 * not prove the signer had ever seen a request at all.
 *
 * WHY IT IS NOT A DecisionReceiptPayload. A refusal is not a decision. Reusing the receipt
 * type would create an artifact a careless reader could mistake for one, and would put a
 * verdict field on something that carries no verdict. It is a distinct structure with a
 * distinct signing domain (see `refusalDigest`), so it can never be presented as a receipt
 * and the vault can never accept it — there is no code path that would even parse it.
 */
export interface RefusalRecord {
    schemaVersion: bigint;
    chainId: bigint;
    vault: Hex;
    /** The action the signer was asked about, so the refusal is attributable to a request. */
    actionHash: Hex;
    /** Hash of the evidence the caller supplied, binding the refusal to that evidence. */
    evidenceHash: Hex;
    requestedVerdict: VerdictName;
    /** keccak256 over the canonical reason-code set, same encoding as a receipt's. */
    reasonCodesHash: Hex;
    refusedAt: bigint;
    signer: Hex;
}

export interface Refusal {
    refused: true;
    /** The findings that blocked attestation, with the tier each fell in. */
    blocking: {code: ReasonCode; severity: Severity}[];
    signerFindings: ReasonCode[];
    requestedVerdict: VerdictName;
    /**
     * The signed refusal artifact (D-012), or null when the request was too malformed to
     * attribute — a payload contradicting its own calldata names no action the signer could
     * honestly say it refused.
     */
    refusalRecord: {record: RefusalRecord; signature: Hex; reasonCodes: string[]} | null;
}

export type EvaluateAndSignResult = ({refused: false} & SignedReceipt) | Refusal;

export interface StatusResult {
    /** The signer's address. The only thing this process ever reveals about its key. */
    signerAddress: Hex;
    vault: Hex;
    chainId: string;
    /** True when the vault is readable and reports this signer as active. */
    ready: boolean;
    notes: string[];
}

