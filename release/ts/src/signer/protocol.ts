export type ReasonCode = keyof typeof REASON_SEVERITY;

export function severityOf(code: ReasonCode): Severity {
    return REASON_SEVERITY[code];
}

/**
 * Whether a set of signer findings permits attesting to `verdict`.
 *
 * Reads as a table rather than nested conditionals because this is the function a
 * reviewer will want to check by eye against the tier documentation above.
 */
export function refusesVerdict(codes: ReasonCode[], verdict: VerdictName): boolean {
    return codes.some((c) => {
        switch (severityOf(c)) {
            case "FATAL":
                return true;
            case "EXECUTABILITY":
                return verdict !== "BLOCK";
            case "CONFORMANCE":
                return verdict === "ALLOW";
        }
    });
}

/**
 * The only shape a reason code may take.
 *
 * Not decoration. `canonicalReasonCodes` joins with "\n" and sorts, and BOTH of those need
 * this constraint to mean anything:
 *
 *   - WITHOUT A DELIMITER BAN the encoding is not injective. The single code
 *     "A\nB" and the pair ["A", "B"] produce identical bytes and therefore an identical
 *     `reasonCodesHash`. Since the code list itself travels outside the receipt and only
 *     the hash is signed, a caller could hand a verifier a list that hashes correctly while
 *     hiding a signer finding inside another element. `reasonCodesHash` is the receipt's
 *     only in-payload commitment to WHY Sentinel decided what it did.
 *
 *   - WITHOUT AN ASCII RESTRICTION the sort is not portable. JavaScript's default sort
 *     compares UTF-16 code units; Python — mandated by D-010 for the independent verifier —
 *     compares code points. The two disagree above U+FFFF, so the same set of codes would
 *     canonicalise differently in the two implementations and the verifier would report a
 *     mismatch on a correct receipt. Restricted to this charset, code-unit and code-point
 *     order coincide, and the D-010 reimplementation is a plain `sorted()`.
 *
 * Both were found by adversarial review rather than by writing the code.
 */
export const REASON_CODE_PATTERN = /^[A-Za-z0-9_.:-]{1,64}$/;

/**
 * Canonical encoding of the reason-code set that `reasonCodesHash` commits to.
 *
 * Sorted, de-duplicated, newline-joined, UTF-8. Deliberately trivial: the D-010 verifier
 * reimplements this from the written schema in another language, and every degree of
 * freedom here is a place two implementations can disagree while both believing they are
 * right. Sorting removes order as a variable; de-duplication removes multiplicity; and
 * `REASON_CODE_PATTERN`, enforced at the RPC boundary, removes the delimiter and the
 * collation as variables.
 *
 * Throws rather than sanitising: silently dropping a malformed code would remove a finding
 * from the record the receipt commits to.
 */
export function canonicalReasonCodes(codes: readonly string[]): string {
    for (const code of codes) {
        if (!REASON_CODE_PATTERN.test(code)) {
            throw new ProtocolError(
                `reason code ${JSON.stringify(code)} is not ${REASON_CODE_PATTERN.source}`,
            );
        }
    }
    return [...new Set(codes)].sort().join("\n");
}

