/**
 * The isolated signer's wire contract (A-005, §3.1, §9 step 3).
 *
 * §3.1: "The signer exposes no generic sign-bytes method. It independently recomputes the
 * canonical action hash, checks the current mandate and policy, confirms an allow verdict,
 * and signs only the defined receipt payload."
 *
 * That sentence is the whole design brief, and this file is where it is made mechanical:
 *
 *   - There are exactly two methods, `status` and `evaluateAndSign`. There is no `sign`,
 *     no `signDigest`, no `signBytes`, and no method that takes a hash and returns a
 *     signature over it. Adding one would void the public "isolated signer" claim.
 *
 *   - `evaluateAndSign` accepts *typed fields*, never a prepared digest. The signer builds
 *     the DecisionReceiptPayload itself and signs the EIP-712 digest it derived. There is
 *     no parameter through which a caller supplies bytes to be signed: `evidenceHash` is
 *     computed from the full bundle, `reasonCodesHash` from the validated code set,
 *     `actionHash` from the typed action, and `decisionId` is generated by the signer.
 *
 *     PRECISELY WHAT THAT DOES AND DOES NOT GUARANTEE, because the first version of this
 *     comment overclaimed and an adversarial review called it: on the ALLOW path every
 *     32-byte field is derived by the signer or checked against the vault's live state. On
 *     the BLOCK and REVIEW paths, `mandateHash`, `policyHash`, and `simulationBlockHash`
 *     may carry values the signer flagged but did not reject — that is the point of those
 *     verdicts, since a receipt that blocks a stale or unverifiable action must be able to
 *     record what was claimed. Such a receipt is EVIDENCE ABOUT A CLAIMED ACTION, never
 *     authority: the vault executes neither verdict, and the discrepancy is recorded in the
 *     reason codes the receipt commits to. What holds unconditionally is the narrower and
 *     more important property — a caller cannot obtain a signature over bytes of its own
 *     choosing, because EIP-712 type and domain separation mean the result is only ever
 *     interpretable as a DecisionReceiptPayload for this chain and this vault.
 *
 *   - Wire numbers are decimal strings, parsed here into bigint. JSON has no integer type
 *     that survives a uint256, and a silently-truncated value in a security payload is a
 *     defect, not an inconvenience.
 *
 * The parsers below are the RPC's input validation. They are strict on purpose: an
 * unrecognised field is an error rather than something quietly ignored, because "the
 * caller sent a field the signer dropped" is exactly how a payload comes to mean two
 * different things to two components.
 */

