export type Hex = `0x${string}`;

/** §5 verdict. Mirrors SentinelTypes.Verdict; BLOCK is the zero value and the default. */
export const VERDICT = {BLOCK: 0, REVIEW: 1, ALLOW: 2} as const;
export type VerdictName = keyof typeof VERDICT;

export function verdictNumber(v: VerdictName): number {
    return VERDICT[v];
}

